export function getTrainingMenusByLevel(level: SkillLevel): TrainingMenu[] {
  return TRAINING_MENUS.filter((menu) => menu.skillLevel === level);
}

export function getTrainingMenuById(id: string): TrainingMenu | undefined {
  return TRAINING_MENUS.find((menu) => menu.id === id);
}

export function getTrainingConceptById(id: string): TrainingConcept | undefined {
  return TRAINING_CONCEPTS.find((concept) => concept.id === id);
}

export function searchTrainingMenus(query: string): TrainingMenu[] {
  const lowerQuery = query.toLowerCase();
  return TRAINING_MENUS.filter(
    (menu) =>
      menu.name.toLowerCase().includes(lowerQuery) ||
      menu.description.toLowerCase().includes(lowerQuery)
  );
}
